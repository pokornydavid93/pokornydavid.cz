type InstanceInput = {
  id: string;
  compositionId: string;
  variantId?: string;
  domainRecipeId?: string;
  layoutRecipeId: string;
  placement: DomainRecipeContract["placementContext"];
  surface: string;
  density?: CompositionInstanceContract["density"];
  motion: CompositionInstanceContract["motionPolicy"];
  sourceFiles: string[];
  routePattern?: string;
  fixtureOrDataVariants?: string[];
};

function instance(input: InstanceInput): CompositionInstanceContract {
  return {
    instanceId: asCompositionInstanceId(input.id),
    compositionId: asCompositionId(input.compositionId),
    structuralVariantId: asVariantId(
      input.variantId ?? `${input.compositionId}.variant.standard`
    ),
    domainRecipeId: input.domainRecipeId
      ? asDomainRecipeId(input.domainRecipeId)
      : undefined,
    layoutRecipeId: asLayoutRecipeId(input.layoutRecipeId),
    placementContext: input.placement,
    surfaceRole: asSurfaceRoleId(input.surface),
    density: input.density ?? "standard",
    motionPolicy: input.motion,
    sourceFiles: input.sourceFiles,
    routePattern: input.routePattern,
    fixtureOrDataVariants: input.fixtureOrDataVariants,
  };
}

const mapped = (sectionKey: string, instanceId: string): CoveredSection => ({
  status: "mapped",
  sectionKey,
  instanceId: asCompositionInstanceId(instanceId),
});

const exception = (
  sectionKey: string,
  exceptionId: string,
  reason: string
): CoveredSection => ({
  status: "exception",
  sectionKey,
  exceptionId,
  reason,
});

const templateOwned = (sectionKey: string, templateRegionId: string): CoveredSection => ({
  status: "template-owned",
  sectionKey,
  templateRegionId: asTemplateRegionId(templateRegionId),
});

const routeSectionFiles = (routePattern: string, sectionKey: string) =>
  sourceFilesForRouteSection(routePattern, sectionKey);

const routeSectionVariants = (routePattern: string, sectionKey: string) =>
  fixtureVariantsForRouteSection(routePattern, sectionKey);

